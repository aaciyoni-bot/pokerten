'use strict';
// Keep the browser and its worker on the server's ordinary public-information
// strategy. The server-only demo guard stays in pokerEngine, never in this copy.
const fs=require('node:fs'),path=require('node:path');
const babel=require('../tests/ui/node_modules/@babel/core');
const root=path.join(__dirname,'..');
const server=fs.readFileSync(path.join(root,'functions/pokerEngine.js'),'utf8');
const names={RANK_V:'BOT_RANK_V',activesOf:'botActives',preflopTier:'botPreflopTier',rangeHandStrength:'botRangeHandStrength',botDiscardIndex:'botDiscardIndex',equityOf:'botSampleEquity',rangeFacing:'botRangeFacing',handBody:'botHandBody',botCallPrice:'botCallPrice',botAction:'botDecision'};
const found=new Map();
for(const node of babel.parseSync(server).program.body){
  if(node.type==='FunctionDeclaration'&&names[node.id.name])found.set(node.id.name,server.slice(node.start,node.end));
  if(node.type==='VariableDeclaration')for(const d of node.declarations)if(names[d.id.name])found.set(d.id.name,`${node.kind} ${server.slice(d.start,d.end)};`);
}
let code=Object.keys(names).map(name=>{if(!found.has(name))throw Error('Missing '+name);return found.get(name);}).join('\n');
const guardStart=code.indexOf('  // The god guard only exists');
const guardEnd=code.indexOf('  // Sizing is priced off the POT',guardStart);
if(guardStart<0||guardEnd<0)throw Error('Server demo-guard boundary changed; review browser information boundary');
code=code.slice(0,guardStart)+'  const hasSomething = () => hasBody;\n'+code.slice(guardEnd);
code=code.replaceAll('blindsOf(S).bb',"((Number(S.settings.blinds) || .5) * 2)").replaceAll('rnd()', 'Math.random()');
for(const name of ['bestScoreFull','getCombinations','pokerDeck','SUITS'])code=code.replaceAll('C.'+name,name);
for(const [from,to] of Object.entries(names))code=code.replace(new RegExp('\\b'+from+'\\b','g'),to);
if(/\bC\.|GOD_FLOOR|trueEquityVs|\brnd\(/.test(code))throw Error('Unexpected server-only dependency in client policy');
const begin='// BEGIN SHARED BOT POLICY — generated by scripts/sync-bot-policy.cjs';
const end='// END SHARED BOT POLICY';
const generated=begin+'\n'+code+`
const simMyEquity = (...args) => {
  const value = botSampleEquity(...args);
  return value == null ? null : Math.round(value * 100);
};
const botPokerMove = (g, t, b) => {
  const move = botDecision({gameState:g, settings:t.settings || {}, players:t.players || {}, priv:{[b.uid]:b.cards || []}}, b.uid);
  return {type:move.action, ...(move.amount == null ? {} : {amt:move.amount})};
};
`+end;
const file=path.join(root,'index.html');
let html=fs.readFileSync(file,'utf8');
let start=html.indexOf(begin),finish;
if(start>=0){finish=html.indexOf(end,start)+end.length;}else{
  start=html.indexOf('/* `range` is what makes the bot notice its opponent.');
  const script=[...html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)].find(m=>m[1].includes('const botPokerMove ='));
  const node=babel.parseSync(script[1]).program.body.find(n=>n.type==='VariableDeclaration'&&n.declarations.some(d=>d.id.name==='botPokerMove'));
  finish=html.indexOf(script[1])+node.end;
}
if(start<0||finish<=start)throw Error('Client strategy boundaries missing');
const updated=html.slice(0,start)+generated+html.slice(finish);
if(process.argv.includes('--check')){if(updated!==html)throw Error('Client bot strategy differs from server: run node scripts/sync-bot-policy.cjs');}
else fs.writeFileSync(file,updated);
