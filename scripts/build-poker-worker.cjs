'use strict';
const fs = require('node:fs');
const path = require('node:path');
const babel = require('../tests/ui/node_modules/@babel/core');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const source = [...html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)].find(m => m[1].includes('const botPokerMove ='))[1];
const names = ['round2','SUITS','CARD_VALUES','pokerDeck','getCombinations','evaluate5Cards','bestScoreFull','deckWithout','simMyEquity','simRealEquity','botRangeFacing','botHandBody','botPreflopTier','botPokerMove'];
const found = new Map();
for (const node of babel.parseSync(source).program.body) {
  if (node.type === 'VariableDeclaration') for (const d of node.declarations) {
    if (names.includes(d.id.name)) found.set(d.id.name, `${node.kind} ${source.slice(d.start,d.end)};`);
  }
  if (node.type === 'FunctionDeclaration' && names.includes(node.id.name)) found.set(node.id.name, source.slice(node.start,node.end));
}
for (const name of names) if (!found.has(name)) throw Error(`Missing ${name}`);
const worker = '// Generated by scripts/build-poker-worker.cjs from the actual client policy.\n'+[...found.values()].join('\n')+`
self.onmessage = ({data}) => {
  try {
    const {id, kind, args} = data;
    const value = kind === 'mine' ? simMyEquity(...args) : kind === 'real' ? simRealEquity(...args) : kind === 'bot' ? botPokerMove(...args) : null;
    self.postMessage({id, value});
  } catch (_) { self.postMessage({id:data.id, value:null}); }
};
`;
const output = path.join(root,'assets/js/poker-equity-worker.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output,'utf8') !== worker) throw Error('Worker differs from client policy: run node scripts/build-poker-worker.cjs');
} else fs.writeFileSync(output, worker);
