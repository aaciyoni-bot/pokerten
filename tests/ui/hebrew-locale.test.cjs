'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const vm=require('node:vm');
const {JSDOM}=require('jsdom');
const {build,englishEntry}=require('../../scripts/locales/client.cjs');

test('English boot ignores the old preference, disabled storage, and old Hebrew links',t=>{
  const root=path.resolve(__dirname,'../..'),out=fs.mkdtempSync(path.join(os.tmpdir(),'pokerten-en-'));
  t.after(()=>fs.rmSync(out,{recursive:true,force:true}));
  build(root,out);
  const en=fs.readFileSync(path.join(out,'index.html'),'utf8');
  assert.equal(englishEntry(en,require('../../assets/release.json').version),en);
  assert.doesNotMatch(en,/data-language-choice|LanguageChoice|hebrew-labels\.js|poker-auth\.he\.js/);
  assert.deepEqual(fs.readdirSync(out).sort(),['he.html','index.html']);
  const doc=new JSDOM(en).window.document;
  assert.equal(doc.documentElement.lang,'en');
  for(const script of doc.querySelectorAll('script:not([src]):not([type="module"])'))new vm.Script(script.textContent);
  const first=doc.querySelector('script').textContent;
  const store=new Map([['pkUiLanguage','he'],['pkResume','table']]);
  vm.runInNewContext(first,{localStorage:{setItem:(k,v)=>store.set(k,v)}});
  assert.equal(store.get('pkUiLanguage'),'en');assert.equal(store.get('pkResume'),'table');
  vm.runInNewContext(first,{get localStorage(){throw Error('unavailable');}});
  const old=new JSDOM(fs.readFileSync(path.join(out,'he.html'),'utf8')).window.document;
  const href='https://localhost/game/he.html?table=abc&uiLang=he#seat',loc=new URL(href);
  let redirected;vm.runInNewContext(old.querySelector('script').textContent,{URL,location:{href,search:loc.search,hash:loc.hash,replace:url=>redirected=url}});
  assert.equal(redirected,'https://localhost/game/index.html?table=abc&uiLang=en#seat');
});
