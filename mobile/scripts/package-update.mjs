import {readFile,writeFile,mkdir,rename} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const mobile=fileURLToPath(new URL('../',import.meta.url));
const release=JSON.parse(await readFile(path.join(mobile,'ota-release.json'),'utf8'));
if(!/^android-\d+$/.test(release.runtime)||!/^\d+\.\d+\.\d+$/.test(release.version))throw Error('Invalid update release identity');
const out=path.resolve(process.argv[2]||path.join(mobile,'../mobile-updates'),release.runtime);
await mkdir(out,{recursive:true});
const temporary=path.join(out,release.version+'.zip');
const result=JSON.parse(execFileSync('npx',['--yes','@capgo/cli@8.99.1','bundle','zip','com.orizis.pokerten','--path','www','--bundle',release.version,'--name',temporary,'--json'],{cwd:mobile,encoding:'utf8',maxBuffer:1048576}));
const bytes=await readFile(temporary);
const checksum=createHash('sha256').update(bytes).digest('hex');
if(result.checksum_algorithm!=='sha256'||result.checksum!==checksum||bytes.length>50000000)throw Error('Invalid update bundle');
const name=release.version+'-'+checksum.slice(0,16)+'.zip';
await rename(temporary,path.join(out,name));
await writeFile(path.join(out,'latest.json'),JSON.stringify({...release,checksum,size:bytes.length,url:'https://pokerten.com/mobile-updates/'+release.runtime+'/'+name},null,2)+'\n');
console.log(JSON.stringify({version:release.version,runtime:release.runtime,size:bytes.length,checksum}));
